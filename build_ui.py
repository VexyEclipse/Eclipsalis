"""Assemble the dependency-free GitHub/loadstring Eclipse UI module."""
from pathlib import Path
import re


def build(root: Path) -> Path:
    ui = root / "UI"
    logo_file = ui / "Assets" / "eclipse-logo.png"
    if logo_file.exists():
        logo_hex = logo_file.read_bytes().hex()
    else:
        # GitHub's text-only authoring distribution retains the exact PNG in the module.
        previous = (root / "EclipseUI.lua").read_text(encoding="utf-8")
        logo_hex = re.search(r'ctx\.logoHex = "([0-9a-f]+)"', previous).group(1)
    parts = [
        "-- Eclipse UI 1.0.0 | https://github.com/VexyEclipse/Eclipsalis\n",
        "-- Generated by build_ui.py. Edit UI/Core.lua, Controls.lua and Advanced.lua.\n",
        "local Library, ctx = (function()\n",
        (ui / "Core.lua").read_text(encoding="utf-8"),
        "\nend)()\n",
        "ctx.logoHex = \"" + logo_hex + "\"\n",
    ]
    for name in ("Controls.lua", "Advanced.lua"):
        parts.extend(("do\nlocal install = (function()\n", (ui / name).read_text(encoding="utf-8"),
                      "\nend)()\ninstall(Library, ctx)\nend\n"))
    parts.append("return Library\n")
    output = root / "EclipseUI.lua"
    output.write_text("".join(parts), encoding="utf-8")
    return output


if __name__ == "__main__":
    print(build(Path(__file__).resolve().parent))
